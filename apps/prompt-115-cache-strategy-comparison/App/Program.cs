using Microsoft.Extensions.Caching.Memory;
using Microsoft.Extensions.Caching.Distributed;
using Microsoft.Extensions.Caching.Hybrid;
using Microsoft.Extensions.DependencyInjection;
await using var nodeA=CacheNodes.Create();await using var nodeB=CacheNodes.Create();
var prefix="course115:"+Guid.NewGuid().ToString("N");
var memoryA=nodeA.GetRequiredService<IMemoryCache>();var memoryB=nodeB.GetRequiredService<IMemoryCache>();
var memoryOrigin=new Origin();
await ReadStrategies.Memory(memoryA,prefix,memoryOrigin);await ReadStrategies.Memory(memoryA,prefix,memoryOrigin);
Check.That(memoryOrigin.Reads==1,"sequential memory-cache hits avoid a second origin read");
if(args.FirstOrDefault()=="memory")Check.That(memoryB.TryGetValue(prefix,out _),"incorrect expectation: memory cache is shared across nodes");
Check.That(!memoryB.TryGetValue(prefix,out _),"memory entries belong to one process cache instance");
var distributedA=nodeA.GetRequiredService<IDistributedCache>();var distributedB=nodeB.GetRequiredService<IDistributedCache>();
var distributedOrigin=new Origin();var distributedKey=prefix+":distributed";
await ReadStrategies.Distributed(distributedA,distributedKey,distributedOrigin);
await ReadStrategies.Distributed(distributedB,distributedKey,distributedOrigin);
Check.That(distributedOrigin.Reads==1,"second node reads the actual shared Redis entry");
var hybridA=nodeA.GetRequiredService<HybridCache>();var hybridB=nodeB.GetRequiredService<HybridCache>();
var hybridOrigin=new Origin();var hybridKey=prefix+":hybrid";
var first=await hybridA.GetOrCreateAsync(hybridKey,ct=>new ValueTask<string>(hybridOrigin.LoadAsync("tenant-a",ct)));
// Wait for the asynchronous L2 population before testing a different node's warm read.
var readyUntil=DateTime.UtcNow.AddSeconds(5);
while(await distributedA.GetAsync(hybridKey) is null && DateTime.UtcNow<readyUntil)await Task.Delay(10);
Check.That(await distributedA.GetAsync(hybridKey) is not null,"HybridCache L2 payload is present before the cross-node warm-read check");
var second=await hybridB.GetOrCreateAsync(hybridKey,ct=>new ValueTask<string>(hybridOrigin.LoadAsync("tenant-a",ct)));
var third=await hybridB.GetOrCreateAsync(hybridKey,ct=>new ValueTask<string>(hybridOrigin.LoadAsync("tenant-a",ct)));
Check.That(first==second && second==third && hybridOrigin.Reads==1,"HybridCache combines shared L2 with per-node local reads");
await distributedA.RemoveAsync(distributedKey);await hybridA.RemoveAsync(hybridKey);
Console.WriteLine("service: observed origin reads: memory=1, distributed=1, hybrid=1; no universal speed ranking");
