using var embeddings = new EmbeddingService();
await using var store = await VectorStore.Open(203);
await store.CreateCollection();
var original = new Document("receipt", "Receipt policy", "Retain receipts for seven years.");
var record = new VectorRecord(original, await embeddings.Generate(original.Body));
await store.Upsert(record);
var updated = original with { Body = "Retain receipts for eight years.", Version = 2 };
var replacement = await embeddings.Generate(updated.Body);
await store.Upsert(new(updated,replacement));
var loadedVector = await store.RetrieveVector(original.Id);
Check.That(loadedVector is not null && loadedVector.Zip(replacement.Vector).All(p=>Math.Abs(p.First-p.Second)<1e-6), "typed vector values round-trip through the native database column");
var loaded = await store.Retrieve(original.Id);
Check.That(loaded?.Version == 2 && loaded.Body == updated.Body, "typed upsert replaces the existing version without duplicating its key");
Check.That(await store.Scalar<long>("SELECT count(*) FROM items") == 1, "the collection contains one current record");
if (!args.Contains("problem")) await store.Delete(original.Id);
bool absent = await store.Retrieve(original.Id) is null;
Console.WriteLine($"CRUD version={loaded!.Version} rowsAfterDelete={await store.Scalar<long>("SELECT count(*) FROM items")} absent={absent}");
Check.That(absent, "deleted records cannot be retrieved", "RAG deleted vector remains retrievable");
await store.Execute("DROP TABLE items");
Check.That(await store.Scalar<bool>("SELECT to_regclass('items') IS NULL"), "collection deletion removes the database table and its indexes");
AiRuntime.Evidence("rag-evidence.json", new { passed = true, version = loaded.Version, absent, collectionDropped = true });
